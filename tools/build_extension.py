#!/usr/bin/env python3
"""Generate extension/decoder.js and the store zip from wikistego.html's core.

    python3 tools/build_extension.py

The decoder is extracted from the same core block as decode.html, so the
carrier/crypto code cannot drift. Regenerate after editing the core:

    npm run build
"""
import pathlib
import re
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "wikistego.html"
EXT = ROOT / "extension"
OUT_JS = EXT / "decoder.js"
DIST = ROOT / "dist-ext"
ZIP = DIST / "wikistego-extension.zip"

CORE = re.compile(
    r"(  /\* ─+ constants ─+ \*/.*?)"
    r"(  /\* ─+ placement ─+ \*/)",
    re.S,
)


def decoder_js() -> str:
    html = SRC.read_text(encoding="utf-8")
    m = CORE.search(html)
    if not m:
        raise SystemExit("could not find the core block in wikistego.html")
    core = m.group(1)

    return (
        "/* Generated by tools/build_extension.py — do not edit.\n"
        "   Source: the core block of wikistego.html. */\n"
        "(function () {\n"
        "  'use strict';\n\n"
        f"{core}\n"
        "  globalThis.__stego = {\n"
        "    decodeText: decodeText, decryptItem: decryptItem,\n"
        "    ALPHABETS: ALPHABETS, F_ENC: F_ENC\n"
        "  };\n"
        "})();\n"
    )


def icons() -> None:
    """Draw the toolbar icons once. Skipped when they already exist."""
    wanted = {16, 32, 48, 128}
    have = {int(p.stem.replace("icon", "")) for p in (EXT / "icons").glob("icon*.png")}
    if wanted <= have:
        return
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("! pillow not installed — keeping existing icons")
        return

    (EXT / "icons").mkdir(parents=True, exist_ok=True)
    for size in sorted(wanted - have):
        scale = 8
        big = size * scale
        im = Image.new("RGBA", (big, big), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        d.rounded_rectangle(
            (0, 0, big - 1, big - 1), radius=int(big * 0.22), fill=(12, 17, 32, 255)
        )
        r = big * 0.16
        cx = cy = big / 2
        d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=(124, 156, 255, 255))
        im.resize((size, size), Image.LANCZOS).save(
            EXT / "icons" / f"icon{size}.png"
        )


def main() -> None:
    OUT_JS.write_text(decoder_js(), encoding="utf-8")
    icons()

    files = [
        "manifest.json",
        "decoder.js",
        "content.js",
        "panel.css",
        "popup.html",
        "popup.css",
        "popup.js",
    ]
    files += [f"icons/icon{n}.png" for n in (16, 32, 48, 128)]

    missing = [f for f in files if not (EXT / f).exists()]
    if missing:
        raise SystemExit("missing extension files: " + ", ".join(missing))

    DIST.mkdir(exist_ok=True)
    with zipfile.ZipFile(ZIP, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(EXT / f, f)

    print(f"wrote {OUT_JS.relative_to(ROOT)} ({OUT_JS.stat().st_size} bytes)")
    print(f"wrote {ZIP.relative_to(ROOT)} ({ZIP.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
